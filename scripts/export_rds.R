# Extract source counts, mapping and QC only; never reuse author embeddings/scores.
args <- commandArgs(trailingOnly=TRUE)
source("scripts/csc_utils.R")
con <- gzcon(gzfile(args[[1]],open="rb"))
obj <- readRDS(con);close(con)
stopifnot(identical(as.character(class(obj)),"cell_data_set"))
ae <- attr(attr(obj,"assays"),".xData")
assays <- attr(get("data",envir=ae,inherits=FALSE),"listData")
if (!"counts" %in% names(assays)) stop("Source counts assay absent")
C <- assays[["counts"]]
if (!identical(as.character(class(C)),"dgCMatrix")) stop("Unexpected counts storage")
csc <- list(i=attr(C,"i"),p=attr(C,"p"),x=attr(C,"x"),Dim=attr(C,"Dim"))
validate_csc(csc)
cols <- attr(attr(obj,"colData"),"listData")
cd <- as.data.frame(cols,stringsAsFactors=FALSE)
cell_ids <- attr(attr(obj,"colData"),"rownames")
if (is.null(cell_ids) || anyDuplicated(cell_ids)) stop("Source cell IDs absent or duplicated")
rr <- attr(obj,"rowRanges")
genes <- attr(attr(rr,"elementMetadata"),"listData")
gene_ids <- as.character(genes$id)
stopifnot(length(gene_ids)==58347L,csc$Dim[1]==length(gene_ids),nrow(cd)==csc$Dim[2],length(cell_ids)==nrow(cd),!anyDuplicated(gene_ids),all(grepl("^ENSG",gene_ids)))
stopifnot(all(cd$Combo==paste0(cd$well_oligo,cd$plate_oligo)),all(cd$culture_plate==cd$plate_oligo),all(cd$cell_type=="A549"),all(as.numeric(cd$time_point)==24))
source_qc <- cd$hash_umis_W>=5 & cd$hash_umis_P>=5 & cd$top_to_second_best_ratio_W>=5 & cd$top_to_second_best_ratio_P>=5 & cd$rt_well!=1
if (anyNA(source_qc) || !all(source_qc)) stop("RDS contains cells outside documented author hash QC")
wells <- read.delim(args[[2]],check.names=FALSE,stringsAsFactors=FALSE)
if (anyDuplicated(wells$Combo)) stop("Selected well keys duplicated")
known <- unique(cd$Combo)
if (!all(known %in% paste0(cd$well_oligo,cd$plate_oligo))) stop("Source well mapping inconsistent")
res <- aggregate_csc(csc,as.character(cd$Combo),as.character(wells$Combo))
out <- args[[3]];dir.create(out,recursive=TRUE,showWarnings=FALSE)
write_gzip_table(data.frame(gene_id=gene_ids,res$counts,check.names=FALSE),file.path(out,"pseudobulk_counts.tsv.gz"))
write.table(data.frame(gene_id=gene_ids,gene_symbol=genes$gene_short_name),file.path(out,"gene_metadata.tsv"),sep="\t",row.names=FALSE,quote=FALSE)
kept <- which(!is.na(res$library_sizes))
keepcols <- c("Combo","well_oligo","plate_oligo","cell_type","replicate","time_point","treatment","dose","dose_pattern","hash_umis_W","hash_umis_P","top_to_second_best_ratio_W","top_to_second_best_ratio_P","rt_well")
cell_qc <- data.frame(cell_id=cell_ids[kept],cd[kept,keepcols],human_UMI=res$library_sizes[kept],human_detected_genes=res$n_genes[kept],check.names=FALSE)
write_gzip_table(cell_qc,file.path(out,"selected_cell_qc.tsv.gz"))
well_qc <- data.frame(Combo=wells$Combo,n_cells=as.integer(res$n_cells),human_UMI=colSums(res$counts),genes_detected=colSums(res$counts>0))
write.table(well_qc,file.path(out,"well_qc.tsv"),sep="\t",row.names=FALSE,quote=FALSE)
info <- data.frame(key=c("source_human_genes","source_A549_nuclei","source_nnz","selected_nuclei","selected_wells","nonempty_selected_wells","selected_UMI","counts_nonnegative_integer","source_hash_QC_all_pass","UMI_conserved","author_embeddings_reused"),value=c(csc$Dim[1],csc$Dim[2],length(csc$x),length(kept),nrow(wells),sum(res$n_cells>0),sum(res$counts),TRUE,TRUE,TRUE,FALSE))
write.table(info,file.path(out,"extraction_summary.tsv"),sep="\t",row.names=FALSE,quote=FALSE)
print(info,row.names=FALSE)
